    if (cp < 0x20u) return s_font5x8_ascii[0];
    if (cp == 0x0401u) return s_font5x8_yo_upper;
    if (cp == 0x0451u) return s_font5x8_yo_lower;
    if (cp >= 0x0410u && cp <= 0x042Fu) return s_font5x8_cyr_upper[cp - 0x0410u];
    if (cp >= 0x0430u && cp <= 0x044Fu) return s_font5x8_cyr_lower[cp - 0x0430u];
